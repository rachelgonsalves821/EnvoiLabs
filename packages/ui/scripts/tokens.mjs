import { readFile, writeFile } from "node:fs/promises";

const input = new URL("../tokens/tokens.json", import.meta.url);
const output = new URL("../src/tokens.css", import.meta.url);
const tokens = JSON.parse(await readFile(input, "utf8"));

function variables(selector, values) {
  return [`${selector} {`, ...values.map(([name, value]) => `  --${name}: ${value};`), "}", ""].join("\n");
}

const themedTokens = [...tokens.color.tokens, ...tokens.shadow.tokens];
const commonTokens = [
  ...tokens.spacing.tokens.map(({ name, value }) => [name, value]),
  ...tokens.radius.tokens.map(({ name, value }) => [name, value]),
  ...Object.entries(tokens.type.families).map(([name, value]) => [`font-${name}`, `var(--envoi-font-${name}, ${value})`]),
  ...tokens.type.groups.flatMap(({ styles, family }) => styles.flatMap((style) => [
    [`text-${style.name}`, `${style.fontWeight} ${style.fontSize}/${style.lineHeight} var(--font-${family})`],
    [`tracking-${style.name}`, style.letterSpacing ?? "normal"],
  ])),
];
const css = [
  "/* Generated by pnpm --filter @envoi-labs/ui gen:tokens. */",
  variables(":root, [data-envoi-font]", commonTokens),
  variables(":root, [data-theme=light]", themedTokens.map(({ name, value }) => [name, value.light])),
  variables("[data-theme=dark]", themedTokens.map(({ name, value }) => [name, value.dark])),
].join("\n");

if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")).replaceAll("\r\n", "\n") !== css) {
    throw new Error("Design tokens are stale. Run pnpm --filter @envoi-labs/ui gen:tokens.");
  }
} else {
  await writeFile(output, css);
}
